// ---------- helpers ----------
const fmt = new Intl.DateTimeFormat("en-US", {
  timeZone: "America/Los_Angeles",
  hour: "2-digit",
  minute: "2-digit",
  hourCycle: "h23",
});

/** Minutes since local midnight in America/Los_Angeles (DST handled by Intl, not a fixed offset). */
export function laMinutes(nowMs: number): number {
  const parts = fmt.formatToParts(new Date(nowMs));
  const h = Number(parts.find((p) => p.type === "hour")?.value ?? "0") % 24;
  const m = Number(parts.find((p) => p.type === "minute")?.value ?? "0");
  return h * 60 + m;
}

export function inWarmWindow(nowMs: number): boolean {
  const m = laMinutes(nowMs);
  return m >= WARM_START_MIN && m < WARM_END_MIN;
}

function json(body: unknown, status = 200): Response {
  return new Response(JSON.stringify(body), {
    status,
    headers: { "Content-Type": "application/json", "Cache-Control": "no-store" },
  });
}
const NOT_LIVE = () => json({ live: false });

function clientIp(request: Request): string {
  const xff = request.headers.get("x-forwarded-for");
  if (xff) return xff.split(",")[0].trim() || "unknown";
  return request.headers.get("x-real-ip")?.trim() || "unknown";
}

export interface Deps {
  fetch: typeof fetch;
  now: () => number;
  env: { PAYCHECK_GUARD_URL?: string; PAYCHECK_GUARD_TOKEN?: string };
}

type GuardAnswer = { verdict: "block" | "pass"; attack_type?: string; evidence?: string; instruction?: string; latency_ms: number };

/** The only place that talks to the guard. Returns null on timeout, network error, non-200 or a malformed answer. */
async function callGuard(deps: Deps, body: GuardRequest): Promise<{ answer: GuardAnswer; roundtrip_ms: number } | null> {
  const base = (deps.env.PAYCHECK_GUARD_URL ?? "").trim().replace(/\/+$/, "");
  const token = deps.env.PAYCHECK_GUARD_TOKEN ?? "";
  if (!base || !token) return null;
  const url = /\/check$/.test(base) ? base : `${base}/check`;
  const ctrl = new AbortController();
  const timer = setTimeout(() => ctrl.abort(), UPSTREAM_TIMEOUT_MS);
  const t0 = deps.now();
  try {
    const res = await deps.fetch(url, {
      method: "POST",
      headers: { "Content-Type": "application/json", "X-Guard-Token": token },
      body: JSON.stringify(body),
      signal: ctrl.signal,
    });
    if (res.status !== 200) return null;
    const raw = (await res.json()) as Record<string, unknown>;
    const verdict = raw.verdict;
    if (verdict !== "block" && verdict !== "pass") return null;
    const roundtrip_ms = Math.max(0, Math.round(deps.now() - t0));
    const str = (v: unknown) => (typeof v === "string" && v.trim() ? v : undefined);
    const trick = str(raw.trick) ?? str(raw.attack_type);
    return {
      answer: {
        verdict,
        attack_type: trick && trick !== "none" ? trick : undefined,
        evidence: str(raw.evidence),
        instruction: str(raw.instruction),
        latency_ms: typeof raw.latency_ms === "number" ? Math.round(raw.latency_ms) : roundtrip_ms,
      },
      roundtrip_ms,
    };
  } catch (err) {
    // Only the error class is logged: never the URL, token or body.
    console.error(`[api/check] guard call failed: ${err instanceof Error ? err.name : "unknown"}`);
    return null;
  } finally {
    clearTimeout(timer);
  }
}

/** Factory so the test can inject fetch, clock and env. Each handler owns its own in-memory limiter state. */
export function createCheckHandler(deps: Deps) {
  const perIp = new Map<string, number[]>();
  let globalCalls: number[] = [];

  return async function handle(request: Request): Promise<Response> {
    if (request.method !== "POST") return json({ error: "method not allowed" }, 405);

    let id: unknown;
    try {
      const text = await request.text();
      if (text.length > 512) return json({ error: "bad request" }, 400);
      id = (JSON.parse(text) as { id?: unknown })?.id;
    } catch {
      return json({ error: "bad request" }, 400);
    }
    if (typeof id !== "string" || !Object.prototype.hasOwnProperty.call(SCENARIOS, id)) {
      return json({ error: "unknown scenario" }, 400);
    }

    const now = deps.now();
    // Outside the warm window: never contact the guard (never wakes it, no spend).
    if (!inWarmWindow(now)) return NOT_LIVE();

    // Per-IP limit.
    const ip = clientIp(request);
    const hits = (perIp.get(ip) ?? []).filter((t) => now - t < PER_IP_WINDOW_MS);
    if (hits.length >= PER_IP_LIMIT) {
      perIp.set(ip, hits);
      return NOT_LIVE();
    }
    hits.push(now);
    perIp.set(ip, hits);
    if (perIp.size > 5000) for (const [k, v] of perIp) if (!v.some((t) => now - t < PER_IP_WINDOW_MS)) perIp.delete(k);

    // Global hourly cap on upstream calls.
    globalCalls = globalCalls.filter((t) => now - t < GLOBAL_WINDOW_MS);
    if (globalCalls.length >= GLOBAL_HOURLY_CAP) return NOT_LIVE();
    globalCalls.push(now);

    const out = await callGuard(deps, SCENARIOS[id]);
    if (!out) return NOT_LIVE();
    return json({ live: true, ...out.answer, roundtrip_ms: out.roundtrip_ms });
  };
}

const handler = createCheckHandler({
  fetch: (...args) => fetch(...args),
  now: () => Date.now(),
  get env() {
    return { PAYCHECK_GUARD_URL: process.env.PAYCHECK_GUARD_URL, PAYCHECK_GUARD_TOKEN: process.env.PAYCHECK_GUARD_TOKEN };
  },
});

export function POST(request: Request): Promise<Response> {
  return handler(request);
}

export function GET(): Response {
  return json({ error: "method not allowed" }, 405);
}
