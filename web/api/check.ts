/**
 * POST /api/check — thin, server-only proxy from the Try it demo to the live PayCheck guard on Modal.
 *
 * Request:  POST {"id": "<one of the 8 Try it scenario ids>"}  (anything else -> 400)
 * Response: {"live": true, verdict, attack_type?, evidence?, instruction?, latency_ms, roundtrip_ms}  only when the guard answered
 *           {"live": false}  in every other case (outside the warm window, rate limited, not configured, timeout, error, non-200)
 *           -> the client then shows the recorded result.
 *
 * The guard only ever receives the stored request body for that scenario (SCENARIOS below, the exact bodies in
 * recorded demo request that produced the recorded results). Visitor text is never forwarded.
 *
 * Upstream contract (the guard server's /check endpoint):
 *   POST <PAYCHECK_GUARD_URL>/check   headers: Content-Type: application/json, X-Guard-Token: <PAYCHECK_GUARD_TOKEN>
 *   body {text, url, action, target}  ->  200 {verdict: "block"|"pass", trick, evidence, instruction, latency_ms}
 *
 * Env (server-only, set in Vercel project settings, never VITE_-prefixed):
 *   PAYCHECK_GUARD_URL    guard base URL (the "/check" path is appended; a URL already ending in /check is used as-is)
 *   PAYCHECK_GUARD_TOKEN  value for the X-Guard-Token header
 *
 * Spend guards: the guard is contacted only 12:15–14:05 America/Los_Angeles (its warm window), with a per-IP limit
 * and a global hourly cap. Limits are best-effort in-memory per function instance (see LIMITS note below).
 * Never logs the token, the guard URL, or request bodies.
 */

